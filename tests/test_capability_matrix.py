"""Capability matrix <-> code traceability.

``docs/capability-matrix.md`` is generated by ``scripts/gen_capability_matrix.py``
from the code registries. These tests fail when:

* the committed file is stale (someone changed code or curated rows without
  regenerating, or hand-edited the file);
* a detector emits a finding category that the detector registry (and hence
  the matrix) does not list, or the registry lists a category nothing emits;
* an ingest parser exists without a matrix row, or a row names a parser that
  does not exist;
* a collector input that ``load_estate`` reads has no row;
* a CSE row names a CSE that neither the code nor any synthetic fixture
  report knows, or a fixture report carries a CSE with no row.
"""

from __future__ import annotations

import ast
import importlib.util
import inspect
import sys
from pathlib import Path
from types import ModuleType

import defusedxml.ElementTree as ET
import pytest

from gpo_lens import danger, ingest, merge, normalize
from gpo_lens.findings import INTRINSIC_DETECTOR_VERSIONS

_ROOT = Path(__file__).resolve().parent.parent
_DOCTOR = _ROOT / "src" / "gpo_lens" / "queries" / "_doctor.py"
_DANGER = _ROOT / "src" / "gpo_lens" / "danger.py"
_FIXTURE_REPORTS = (
    _ROOT / "tests" / "fixtures" / "AllGPOs.xml",
    _ROOT / "tests" / "golden_estate" / "AllGPOs.xml",
    _ROOT / "tests" / "fixtures" / "cse_audit_pki" / "report.xml",
)
_CATCH_ALL = "(any other CSE)"

# ingest functions that are not per-input or per-setting readers: the dispatcher
# and structural helpers that the CSE and input rows' readers sit under.
_STRUCTURAL = {
    "_parse_settings": "dispatches each ExtensionData block to the CSE parsers",
    "_parse_links": "GPO link rows inside AllGPOs.xml (part of parse_report)",
    "_parse_delegation": "GPO ACL rows inside AllGPOs.xml (part of parse_report)",
    "_parse_single_gpo": "one <GPO> element (part of parse_report)",
    "_parse_gplink": "gPLink attribute text (part of parse_inheritance / sites)",
    "parse_report_xml": "bytes entry point of parse_report (baseline/golden uploads)",
}


def _load_generator() -> ModuleType:
    path = _ROOT / "scripts" / "gen_capability_matrix.py"
    spec = importlib.util.spec_from_file_location("gen_capability_matrix", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # @dataclass resolves the defining module through sys.modules.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


gen = _load_generator()


def test_committed_matrix_is_current() -> None:
    committed = (_ROOT / "docs" / "capability-matrix.md").read_text(encoding="utf-8")
    assert committed == gen.render(), (
        "docs/capability-matrix.md is stale: run `python scripts/gen_capability_matrix.py`"
    )


def test_generator_refuses_registry_drift(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setitem(INTRINSIC_DETECTOR_VERSIONS, "phantom_detector", "1")
    with pytest.raises(ValueError, match="phantom_detector"):
        gen.render()


def _keyword_values(tree: ast.AST, call: str, keyword: str) -> list[ast.expr]:
    values = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == call:
            values.extend(kw.value for kw in node.keywords if kw.arg == keyword)
    return values


def _danger_categories() -> set[str]:
    tree = ast.parse(_DANGER.read_text(encoding="utf-8"))
    found: set[str] = set()
    for value in _keyword_values(tree, "DangerFinding", "check_id"):
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            found.add(f"danger:{value.value}")
        elif ast.unparse(value) == "rule.id":
            found.add("danger:setting_rules")
        else:
            pytest.fail(f"unrecognized danger check_id expression: {ast.unparse(value)}")
    return found


def _doctor_categories() -> set[str]:
    tree = ast.parse(_DOCTOR.read_text(encoding="utf-8"))
    # String literals assigned to a local named `category` (the per-setting
    # evidence categories chosen in a branch before one DoctorFinding call).
    assigned = {
        node.value.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "category" for t in node.targets)
        and isinstance(node.value, ast.Constant)
        and node.value.value
    }
    found: set[str] = set()
    for value in _keyword_values(tree, "DoctorFinding", "category"):
        if isinstance(value, ast.Constant):
            found.add(value.value)
        elif isinstance(value, ast.Name) and value.id == "category":
            found |= assigned
        elif isinstance(value, ast.JoinedStr):
            prefix = value.values[0]
            assert isinstance(prefix, ast.Constant), ast.unparse(value)
            if prefix.value == "broken_ref:":
                found.add("broken_ref:*")
            elif prefix.value == "danger:":
                found |= _danger_categories()
            else:
                pytest.fail(f"unrecognized category f-string: {ast.unparse(value)}")
        else:
            pytest.fail(f"unrecognized category expression: {ast.unparse(value)}")
    return found


def test_every_emitted_category_has_a_matrix_row_and_vice_versa() -> None:
    emitted = _doctor_categories()
    registry = set(INTRINSIC_DETECTOR_VERSIONS)
    assert emitted - registry == set(), (
        f"emitted but not in the registry/matrix: {emitted - registry}"
    )
    assert registry - emitted == set(), (
        f"in the registry/matrix but never emitted: {registry - emitted}"
    )
    assert set(gen.DETECTOR_DESCRIPTIONS) == registry


def test_danger_rule_ids_do_not_shadow_structural_checks() -> None:
    structural = {c.removeprefix("danger:") for c in _danger_categories()}
    rule_ids = {rule.id for rule in danger.load_danger_rules()}
    assert rule_ids and not rule_ids & structural


def _module_functions(module: ModuleType) -> set[str]:
    return {
        name
        for name, obj in vars(module).items()
        if inspect.isfunction(obj) and obj.__module__ == module.__name__
    }


def test_every_ingest_reader_has_a_row_and_rows_name_real_readers() -> None:
    cited = {p for row in gen.CSE_ROWS for p in row.parsers} | {r for _, r, _ in gen.INPUT_ROWS}
    functions = _module_functions(ingest)
    assert cited <= functions, f"matrix rows cite missing ingest functions: {cited - functions}"
    readers = {
        f
        for f in functions
        if f.startswith(("parse_", "_parse_", "augment_")) or f == "_readable_identity"
    }
    assert set(_STRUCTURAL) <= readers, set(_STRUCTURAL) - readers
    uncited = readers - cited - set(_STRUCTURAL)
    assert not uncited, f"ingest readers with no capability-matrix row: {sorted(uncited)}"


def test_every_load_estate_input_has_a_row() -> None:
    tree = ast.parse(inspect.getsource(ingest.load_estate))
    literals = {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and node.value.endswith((".json", ".xml"))
    }
    rows = " ".join(name for name, _, _ in gen.INPUT_ROWS)
    missing = sorted(name for name in literals if name not in rows)
    assert literals and not missing, f"load_estate inputs with no matrix row: {missing}"


def _fixture_cse_names() -> set[str]:
    names: set[str] = set()
    for report in _FIXTURE_REPORTS:
        for elem in ET.parse(report).getroot().iter():
            if elem.tag.rsplit("}", 1)[-1] != "ExtensionData":
                continue
            for child in elem:
                if child.tag.rsplit("}", 1)[-1] == "Name" and child.text:
                    names.add(child.text.strip())
    return names


def _code_cse_names() -> set[str]:
    names = set(normalize.REGISTRY_CSES)
    names |= merge._SCRIPTS_CSES | merge._GPP_CSES | merge._IPSEC_WIRELESS_CSES
    names |= merge._FOLDER_REDIRECTION_CSES | {"security", "software installation"}
    names |= {ingest._AUDIT_CSE.lower(), "public key", "internet explorer maintenance"}
    return names


def test_cse_rows_name_cses_the_code_or_fixtures_know() -> None:
    known = {n.lower() for n in _fixture_cse_names()} | _code_cse_names()
    rows = [row.name for row in gen.CSE_ROWS if row.name != _CATCH_ALL]
    unknown = [name for name in rows if name.strip().lower() not in known]
    assert not unknown, f"CSE rows not grounded in code or fixtures: {unknown}"
    assert len(rows) == len(set(rows))


def test_every_fixture_cse_has_a_row() -> None:
    rows = {row.name for row in gen.CSE_ROWS}
    missing = sorted(_fixture_cse_names() - rows)
    assert not missing, f"fixture CSEs with no capability-matrix row: {missing}"
